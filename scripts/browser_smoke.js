// Runs only against the temporary database/server created by smoke_test.py.
const fs = require('fs');
const assert = require('node:assert/strict');
const { chromium } = require('playwright');
(async () => {
  const credentials = JSON.parse(fs.readFileSync(process.env.PFPLUS_SMOKE_CREDENTIALS, 'utf8'));
  const browser = await chromium.launch({executablePath:process.env.CHROMIUM_PATH || '/usr/bin/chromium',headless:true,args:['--no-sandbox']});
  const page = await browser.newPage({viewport:{width:1440,height:1050}});
  page.setDefaultTimeout(30000);
  const base = process.env.PFPLUS_SMOKE_URL || 'http://127.0.0.1:8001';
  const errors=[]; page.on('pageerror',e=>errors.push(e.message));
  await page.goto(base+'/login/');
  await page.locator('[name=username]').fill(credentials.username);
  await page.locator('[name=password]').fill(credentials.password);
  await page.locator('button[type=submit], button.primary').click();
  await page.waitForURL(base+'/');
  assert.match(await page.locator('h1').textContent(), /Финансово табло/);
  assert.equal(await page.locator('.sidebar').evaluate(e=>getComputedStyle(e).position),'fixed','Stylesheet did not load');
  await page.screenshot({path:'runtime/visual/dashboard-desktop.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:'runtime/visual/dashboard-mobile.png',fullPage:true});
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),'Mobile page overflows');
  await page.setViewportSize({width:1440,height:1050});
  await page.goto(base+'/new/course/');
  await page.locator('[name=title]').fill('Проверка на основния работен процес');
  await page.locator('[name=start]').fill('2030-01-15T10:00');
  await page.locator('[name=status]').selectOption('open');
  await page.locator('[name=expected_count]').fill('10');
  await page.locator('[name=expected_price]').fill('90.00');
  await page.locator('[name=expected_cost]').fill('100.00');
  await page.getByRole('button',{name:'Запази записа'}).click();
  await page.waitForURL(/\/courses\/\d+\/$/);
  const courseId=page.url().match(/courses\/(\d+)/)[1];
  await page.goto(base+'/new/price/?course='+courseId);
  await page.locator('[name=name]').fill('Стандартна');
  await page.locator('[name=amount]').fill('90');
  await page.getByRole('button',{name:'Запази записа'}).click();
  await page.waitForURL(base+'/courses/'+courseId+'/');
  await page.goto(base+'/new/participant/?course='+courseId);
  await page.locator('[name=name]').fill('Тестов Участник');
  await page.locator('[name=email]').fill('smoke@example.com');
  await page.locator('[name=due]').fill('90');
  await page.getByRole('button',{name:'Запази записа'}).click();
  await page.waitForURL(base+'/courses/'+courseId+'/');
  for(let i=1;i<=2;i++){
    await page.goto(base+'/new/payment/?course='+courseId);
    await page.locator('[name=date]').fill('2030-01-15');
    const participantOption = await page.locator('[name=participant] option').allTextContents();
    const participantText=participantOption.find(s=>s.includes('Тестов Участник'));
    await page.locator('[name=participant]').selectOption({label:participantText});
    await page.locator('[name=payer]').fill('Тестов Участник');
    await page.locator('[name=amount]').fill('45');
    await page.locator('[name=reference]').fill('BROWSER-SMOKE-'+i);
    await page.getByRole('button',{name:'Запази записа'}).click();
    await page.waitForURL(/\/register\/payments\/$/);
    await page.getByRole('row').filter({hasText:'BROWSER-SMOKE-'+i}).getByRole('button',{name:'Потвърди получаването'}).click();
    await page.waitForLoadState('networkidle');
    await page.goto(base+'/courses/'+courseId+'/');
    assert((await page.getByRole('row').filter({hasText:'Тестов Участник'}).textContent()).includes(i===1?'Частично платил':'Платил'));
  }
  await page.goto(base+'/new/expense/');
  await page.locator('[name=date]').fill('2030-01-15');
  await page.locator('[name=course]').selectOption(courseId);
  await page.locator('[name=payee]').fill('Тестов Лектор');
  await page.locator('[name=category]').selectOption('external');
  await page.locator('[name=amount]').fill('20');
  await page.locator('[name=state]').selectOption('approved');
  await page.getByRole('button',{name:'Запази записа'}).click();
  await page.waitForURL(/\/register\/expenses\/$/);
  await page.goto(base+'/new/period/');
  await page.locator('[name=title]').fill('Януари 2030 — тест');
  await page.locator('[name=start]').fill('2030-01-01');
  await page.locator('[name=end]').fill('2030-01-31');
  await page.getByRole('button',{name:'Запази записа'}).click();
  await page.waitForURL(/\/register\/periods\/$/);
  await page.getByRole('link',{name:'Януари 2030 — тест',exact:true}).click();
  const generation = page.getByRole('button',{name:'Генерирай DOCX / PDF проекти'});
  await generation.click({timeout:90000});
  await page.waitForURL(/\/documents\/\d+\/$/,{timeout:90000});
  assert((await page.locator('h1').textContent()).includes('Януари 2030'));
  const pdfLink=page.getByRole('link',{name:/Общ документ · PDF/});
  assert.equal(await pdfLink.count(),1);
  const response=await page.request.get(base+await pdfLink.getAttribute('href'));
  assert.equal(response.status(),200);
  assert((await response.body()).subarray(0,4).toString()==='%PDF');
  await page.goto(base+'/register/discrepancies/');
  await page.screenshot({path:'runtime/visual/discrepancies.png',fullPage:true});
  await page.goto(base+'/google/');
  assert((await page.locator('body').textContent()).includes('Не е свързан акаунт'));
  assert.deepEqual(errors,[]);
  console.log('PASS: real login, desktop/mobile, course, price, participant, partial/full payments, expense, period, DOCX/PDF, Google connection status.');
  await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
